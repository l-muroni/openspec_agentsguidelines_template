#!/usr/bin/env bash
# ============================================================
# ROLE: Rigenera comandi e skill OpenSpec in .opencode/ e .cursor/ dal profilo pinnato
# DEPENDS ON: config/openspec-profile.json, @fission-ai/openspec (devDependency)
# USED BY: npm run openspec-update, CI (--check)
# KEY DECISIONS: il profilo dei workflow vive nel repo, non nel config globale di chi
#   lancia il comando; --check rigenera in una cartella temporanea e confronta
# GOTCHAS: imposta il profilo globale di OpenSpec (~/.config/openspec) ai valori pinnati.
#   Usa sempre la CLI locale di node_modules, mai una versione globale.
#   Confronta solo gli artefatti OpenSpec sotto .cursor/ (opsx-* e openspec-*),
#   lasciando fuori rules/, grill, update-context e le skill custom.
# LAST UPDATED: 2026-10-14 - anche Cursor (.cursor/commands e skills OpenSpec)
# ============================================================
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
CLI="$ROOT/node_modules/.bin/openspec"
PROFILE="$ROOT/config/openspec-profile.json"
export OPENSPEC_TELEMETRY=0

[ -x "$CLI" ] || { echo "❌  CLI OpenSpec non trovata: eseguire npm ci"; exit 1; }

WORKFLOWS=$(node -e "console.log(JSON.stringify(require('$PROFILE').workflows))")

# Apply the pinned profile to the global OpenSpec config
"$CLI" config set telemetry.enabled false >/dev/null
"$CLI" config set profile custom >/dev/null
"$CLI" config set workflows "$WORKFLOWS" >/dev/null

# Compare OpenSpec-managed Cursor artifacts (opsx commands + openspec skills)
diff_cursor_openspec() {
  local left="$1"
  local right="$2"
  local drift=0

  # Commands generated by OpenSpec
  local left_cmds=()
  local right_cmds=()
  shopt -s nullglob
  left_cmds=("$left"/commands/opsx-*.md)
  right_cmds=("$right"/commands/opsx-*.md)
  shopt -u nullglob

  if [ "${#left_cmds[@]}" -ne "${#right_cmds[@]}" ]; then
    echo "  comandi opsx: ${#left_cmds[@]} nel repo vs ${#right_cmds[@]} attesi"
    drift=1
  fi

  for f in "${left_cmds[@]}"; do
    local base
    base=$(basename "$f")
    if [ ! -f "$right/commands/$base" ]; then
      echo "  manca in atteso: .cursor/commands/$base"
      drift=1
    elif ! diff -q "$f" "$right/commands/$base" >/dev/null; then
      echo "  diverso: .cursor/commands/$base"
      drift=1
    fi
  done

  for f in "${right_cmds[@]}"; do
    local base
    base=$(basename "$f")
    if [ ! -f "$left/commands/$base" ]; then
      echo "  manca nel repo: .cursor/commands/$base"
      drift=1
    fi
  done

  # Skills generated by OpenSpec
  local left_skills=()
  local right_skills=()
  shopt -s nullglob
  left_skills=("$left"/skills/openspec-*)
  right_skills=("$right"/skills/openspec-*)
  shopt -u nullglob

  if [ "${#left_skills[@]}" -ne "${#right_skills[@]}" ]; then
    echo "  skill openspec: ${#left_skills[@]} nel repo vs ${#right_skills[@]} attese"
    drift=1
  fi

  for d in "${left_skills[@]}"; do
    local name
    name=$(basename "$d")
    if [ ! -d "$right/skills/$name" ]; then
      echo "  manca in atteso: .cursor/skills/$name"
      drift=1
    elif ! diff -rq "$d" "$right/skills/$name" >/dev/null; then
      echo "  diverso: .cursor/skills/$name"
      drift=1
    fi
  done

  for d in "${right_skills[@]}"; do
    local name
    name=$(basename "$d")
    if [ ! -d "$left/skills/$name" ]; then
      echo "  manca nel repo: .cursor/skills/$name"
      drift=1
    fi
  done

  return "$drift"
}

if [ "${1:-}" = "--check" ]; then
  TMP=$(mktemp -d)
  trap 'rm -rf "$TMP"' EXIT
  cp -R "$ROOT/openspec" "$ROOT/.opencode" "$TMP/"
  if [ -d "$ROOT/.cursor" ]; then
    cp -R "$ROOT/.cursor" "$TMP/"
  fi
  (cd "$TMP" && "$CLI" update >/dev/null 2>&1)

  FAILED=0
  if ! diff -r "$ROOT/.opencode" "$TMP/.opencode" >/dev/null; then
    echo "❌  .opencode/ non corrisponde al profilo pinnato in config/openspec-profile.json"
    diff -rq "$ROOT/.opencode" "$TMP/.opencode" | sed 's|'"$TMP"'|<atteso>|; s|'"$ROOT"'/||' || true
    FAILED=1
  fi

  if [ -d "$ROOT/.cursor" ]; then
    if ! diff_cursor_openspec "$ROOT/.cursor" "$TMP/.cursor"; then
      echo "❌  .cursor/ (opsx-* / openspec-*) non corrisponde al profilo pinnato in config/openspec-profile.json"
      FAILED=1
    fi
  else
    echo "❌  .cursor/ assente: eseguire npm run openspec-update dopo openspec init --tools cursor"
    FAILED=1
  fi

  if [ "$FAILED" -ne 0 ]; then
    echo "    Eseguire: npm run openspec-update"
    exit 1
  fi
  echo "✅  Comandi e skill OpenSpec allineati al profilo $WORKFLOWS (OpenCode + Cursor)"
  exit 0
fi

(cd "$ROOT" && "$CLI" update)
